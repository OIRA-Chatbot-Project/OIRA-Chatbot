"""
Repository Protocol interfaces (ports).

Service layer depends on these abstractions — not on SQLAlchemy implementations.
Concrete implementations live alongside each protocol in this package.
"""
from typing import Protocol, Optional, List

# Forward-reference type aliases (avoid circular imports from ORM models)
# The concrete implementations import ORM models directly.


class UserRepository(Protocol):
    def get_by_clerk_id(self, clerk_user_id: str): ...
    def get_by_internal_id(self, user_id: int): ...
    def create(self, clerk_user_id: str, email: str, name: Optional[str]): ...
    def update(self, user): ...


class SessionRepository(Protocol):
    def get_by_id(self, session_id: str): ...
    def get_by_id_and_user(self, session_id: str, user_id: int): ...
    def list_for_user_with_message_counts(self, user_id: int) -> List: ...
    def create(self, session_id: str, user_id: int): ...
    def update(self, session): ...
    def delete(self, session) -> None: ...


class MessageRepository(Protocol):
    def get_for_session(self, session_id: str) -> List: ...
    def get_history_before(self, session_id: str, before_id: int, limit: int) -> List: ...
    def get_by_id(self, message_id: int): ...
    def count_for_session(self, session_id: str) -> int: ...
    def get_older_than_window(self, session_id: str, keep_count: int) -> List: ...
    def create(self, session_id: str, role: str, content: str, citations: Optional[str]): ...
    def update(self, message): ...
    def delete_after(self, session_id: str, after_id: int) -> List[int]: ...


class FeedbackRepository(Protocol):
    def create(self, session_id: str, message_id: int, rating: int, note: Optional[str]): ...
    def delete_for_messages(self, message_ids: List[int]) -> None: ...
